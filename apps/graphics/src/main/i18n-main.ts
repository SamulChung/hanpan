type MainStringKey =
  | 'dlgSaveTitle'
  | 'dlgExportTitle'
  | 'dlgPickImageTitle'
  | 'filterImages'
  | 'untitledFile'
  | 'untitledPhoto'
  | 'untitledIllust'
  | 'closeUnsavedMsg'
  | 'closeUnsavedNamedMsg'
  | 'closeUnsavedDetail'
  | 'btnSave'
  | 'btnDontSave'
  | 'btnCancel'
  | 'replaceExistingMsg'
  | 'replaceExistingDetail'
  | 'btnReplace'

/** A dialog text in the current interface language. */
export function tm(key: MainStringKey): string {
  return tDlg(getUiLang(), key)
}

/**
 * The close question's first line: the document by name ("'photo.jpg' has
 * unsaved changes.") so a prompt that comes up while quitting says which tab
 * it is about; the plain line when there is no name.
 */
export function closeUnsavedMessage(name: string | null | undefined): string {
  const trimmed = name?.trim()
  if (!trimmed) return tm('closeUnsavedMsg')
  return tDlg(getUiLang(), 'closeUnsavedNamedMsg', { name: trimmed })
}
